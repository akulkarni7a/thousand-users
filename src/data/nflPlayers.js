export function filterPlayers(players, query, guessedIds = []) {
  if (!query || query.trim() === '') return []
  const cleanQuery = query.trim().toLowerCase()
  const guessedSet = new Set(guessedIds.map((id) => String(id)))

  return players.filter((player) => {
    if (guessedSet.has(String(player.id))) return false
    const nameMatch = player.name.toLowerCase().includes(cleanQuery)
    const teamMatch = player.team.toLowerCase().includes(cleanQuery)
    const abbrMatch = player.teamAbbr.toLowerCase().includes(cleanQuery)
    return nameMatch || teamMatch || abbrMatch
  })
}

export function comparePlayers(guess, target) {
  if (!guess || !target) return null

  const isCorrect = String(guess.id) === String(target.id)

  // Team clue
  let teamMatch = 'incorrect'
  if (guess.team === target.team) {
    teamMatch = 'correct'
  } else if (guess.conference === target.conference) {
    teamMatch = 'close'
  }

  // Conference clue
  const confMatch = guess.conference === target.conference ? 'correct' : 'incorrect'

  // Division clue
  let divMatch = 'incorrect'
  if (guess.conference === target.conference && guess.division === target.division) {
    divMatch = 'correct'
  } else if (guess.conference === target.conference || guess.division === target.division) {
    divMatch = 'close'
  }

  // Position clue
  let posMatch = 'incorrect'
  if (guess.position === target.position) {
    posMatch = 'correct'
  } else if (guess.sideOfBall === target.sideOfBall) {
    posMatch = 'close'
  }

  // Side of ball clue
  const sideMatch = guess.sideOfBall === target.sideOfBall ? 'correct' : 'incorrect'

  // Age clue
  let ageMatch = 'incorrect'
  let ageDir = ''
  if (guess.age === target.age) {
    ageMatch = 'correct'
  } else {
    ageDir = target.age > guess.age ? '↑' : '↓'
    if (Math.abs(guess.age - target.age) <= 2) {
      ageMatch = 'close'
    }
  }

  // Number clue
  let numMatch = 'incorrect'
  let numDir = ''
  if (guess.number === target.number) {
    numMatch = 'correct'
  } else {
    numDir = target.number > guess.number ? '↑' : '↓'
    if (Math.abs(guess.number - target.number) <= 5) {
      numMatch = 'close'
    }
  }

  // Pro Bowls clue
  let pbMatch = 'incorrect'
  let pbDir = ''
  if (guess.proBowls === target.proBowls) {
    pbMatch = 'correct'
  } else {
    pbDir = target.proBowls > guess.proBowls ? '↑' : '↓'
    if (Math.abs(guess.proBowls - target.proBowls) <= 1) {
      pbMatch = 'close'
    }
  }

  return {
    isCorrect,
    team: { value: guess.teamAbbr, match: teamMatch },
    conference: { value: guess.conference, match: confMatch },
    division: { value: guess.division, match: divMatch },
    position: { value: guess.position, match: posMatch },
    sideOfBall: { value: guess.sideOfBall, match: sideMatch },
    age: { value: guess.age, match: ageMatch, direction: ageDir },
    number: { value: guess.number, match: numMatch, direction: numDir },
    proBowls: { value: guess.proBowls, match: pbMatch, direction: pbDir },
  }
}

export function getDailyPlayer(dateStr) {
  const targetDate = dateStr || new Date().toISOString().slice(0, 10)
  let hash = 0
  for (let i = 0; i < targetDate.length; i++) {
    hash = (hash << 5) - hash + targetDate.charCodeAt(i)
    hash |= 0
  }
  const index = Math.abs(hash) % NFL_PLAYERS.length
  return NFL_PLAYERS[index]
}

export function getRandomPlayer(excludeId = null) {
  const available = NFL_PLAYERS.filter((p) => String(p.id) !== String(excludeId))
  const index = Math.floor(Math.random() * available.length)
  return available[index] || NFL_PLAYERS[0]
}

export function getPuzzleNumber(dateStr) {
  const startDate = new Date('2026-01-01')
  const targetDate = dateStr ? new Date(dateStr) : new Date()
  const diffTime = Math.abs(targetDate - startDate)
  const diffDays = Math.floor(diffTime / (1000 * 60 * 60 * 24))
  return diffDays + 1
}

export function generateShareCard(guesses, targetPlayer, gameMode = 'daily', puzzleNum = 1, isWin = false) {
  const guessCountText = isWin ? `${guesses.length}/8` : 'X/8'
  const title = gameMode === 'daily' ? `Gridiron Guesser #${puzzleNum}` : `Gridiron Guesser Practice`
  
  const rows = guesses.map((g) => {
    const comp = comparePlayers(g, targetPlayer)
    if (!comp) return ''

    const toEmoji = (match, dir = '') => {
      let baseEmoji = '⬛'
      if (match === 'correct') baseEmoji = '🟩'
      else if (match === 'close') baseEmoji = '🟨'
      
      if (dir === '↑') return '⬆️'
      if (dir === '↓') return '⬇️'
      return baseEmoji
    }

    return [
      toEmoji(comp.team.match),
      toEmoji(comp.conference.match),
      toEmoji(comp.division.match),
      toEmoji(comp.position.match),
      toEmoji(comp.sideOfBall.match),
      toEmoji(comp.age.match, comp.age.direction),
      toEmoji(comp.number.match, comp.number.direction),
      toEmoji(comp.proBowls.match, comp.proBowls.direction),
    ].join('')
  })

  return `${title} ${guessCountText}\n\n${rows.join('\n')}\n\nhttps://gridiron-guesser.app`
}
